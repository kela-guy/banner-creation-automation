export function t(locale: Locale, key: StringKey): string {
  return translations[locale][key] as string;
}

export type PanelKey = keyof typeof panelEn;

export function panelT(locale: Locale, key: PanelKey): string {
  return translations[locale].panel[key];
}

export function pipelineLabel(locale: Locale, nodeId: PipelineNodeId): string {
  return translations[locale].pipeline[nodeId].label;
}

export function pipelineSummary(locale: Locale, nodeId: PipelineNodeId): string {
  return translations[locale].pipeline[nodeId].summary;
}
